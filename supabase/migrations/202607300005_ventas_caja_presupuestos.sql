-- RLS: caja y configuración solo admin/recepción para escritura.
do $$ declare t text; begin
 foreach t in array array['ventas','detalle_ventas','presupuestos'] loop
  execute format('alter table public.%I enable row level security',t);
  execute format('drop policy if exists %I on public.%I',t||'_leer',t);
  execute format('create policy %I on public.%I for select to authenticated using (public.mi_rol() is not null)',t||'_leer',t);
  execute format('drop policy if exists %I on public.%I',t||'_insertar',t);
  execute format('create policy %I on public.%I for insert to authenticated with check (public.mi_rol() in (''admin'',''recepcion'',''tecnico''))',t||'_insertar',t);
  execute format('drop policy if exists %I on public.%I',t||'_actualizar',t);
  execute format('create policy %I on public.%I for update to authenticated using (public.mi_rol() in (''admin'',''recepcion'',''tecnico'')) with check (public.mi_rol() in (''admin'',''recepcion'',''tecnico''))',t||'_actualizar',t);
  execute format('drop policy if exists %I on public.%I',t||'_eliminar',t);
  execute format('create policy %I on public.%I for delete to authenticated using (public.es_admin())',t||'_eliminar',t);
  execute format('grant select,insert,update,delete on public.%I to authenticated',t);
 end loop;
end $$;

alter table public.movimientos_caja enable row level security;
drop policy if exists movimientos_caja_leer on public.movimientos_caja;
create policy movimientos_caja_leer on public.movimientos_caja for select to authenticated using (public.mi_rol() in ('admin','recepcion'));
drop policy if exists movimientos_caja_insertar on public.movimientos_caja;
create policy movimientos_caja_insertar on public.movimientos_caja for insert to authenticated with check (public.mi_rol() in ('admin','recepcion','tecnico'));
drop policy if exists movimientos_caja_actualizar on public.movimientos_caja;
create policy movimientos_caja_actualizar on public.movimientos_caja for update to authenticated using (public.mi_rol() in ('admin','recepcion')) with check (public.mi_rol() in ('admin','recepcion'));
drop policy if exists movimientos_caja_eliminar on public.movimientos_caja;
create policy movimientos_caja_eliminar on public.movimientos_caja for delete to authenticated using (public.es_admin());
grant select,insert,update,delete on public.movimientos_caja to authenticated;

alter table public.configuracion_negocio enable row level security;
drop policy if exists configuracion_negocio_leer on public.configuracion_negocio;
create policy configuracion_negocio_leer on public.configuracion_negocio for select to authenticated using (public.mi_rol() is not null);
drop policy if exists configuracion_negocio_escribir on public.configuracion_negocio;
create policy configuracion_negocio_escribir on public.configuracion_negocio for all to authenticated using (public.mi_rol() in ('admin','recepcion')) with check (public.mi_rol() in ('admin','recepcion'));
grant select,insert,update,delete on public.configuracion_negocio to authenticated;
grant usage,select on all sequences in schema public to authenticated;

