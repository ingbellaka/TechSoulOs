begin;

create table if not exists public.ventas (
  id bigint generated by default as identity primary key,
  folio text not null unique,
  cliente_nombre text not null default 'Público general',
  cliente_telefono text default '',
  total numeric(12,2) not null default 0 check (total >= 0),
  anticipo numeric(12,2) not null default 0 check (anticipo >= 0),
  pagado numeric(12,2) not null default 0 check (pagado >= 0),
  saldo numeric(12,2) not null default 0 check (saldo >= 0),
  metodo_pago text default 'Efectivo',
  estado_pago text not null default 'Pendiente',
  estado_entrega text not null default 'Entregado',
  notas text default '',
  fecha_venta timestamptz not null default now(),
  presupuesto_id bigint,
  creado_por uuid default auth.uid() references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint ventas_montos_validos check (pagado <= total and anticipo <= total)
);
create index if not exists ventas_fecha_idx on public.ventas(fecha_venta desc);
create index if not exists ventas_estado_pago_idx on public.ventas(estado_pago);

create table if not exists public.detalle_ventas (
  id bigint generated by default as identity primary key,
  venta_id bigint not null references public.ventas(id) on delete cascade,
  tipo_item text not null default 'producto',
  producto_id bigint references public.productos(id) on delete set null,
  descripcion text not null,
  cantidad numeric(12,2) not null default 1 check (cantidad > 0),
  precio_unitario numeric(12,2) not null default 0 check (precio_unitario >= 0),
  subtotal numeric(12,2) not null default 0 check (subtotal >= 0),
  costo_estimado numeric(12,2) not null default 0 check (costo_estimado >= 0),
  proveedor text default '',
  fecha_estimada date,
  estado_entrega text not null default 'entregado',
  notas text default '',
  created_at timestamptz not null default now()
);
create index if not exists detalle_ventas_venta_idx on public.detalle_ventas(venta_id);

create table if not exists public.movimientos_caja (
  id bigint generated by default as identity primary key,
  tipo text not null check (tipo in ('Entrada','Salida')),
  concepto text not null,
  monto numeric(12,2) not null check (monto > 0),
  metodo_pago text default 'Efectivo',
  referencia_tipo text,
  referencia_id text,
  notas text default '',
  fecha_movimiento timestamptz not null default now(),
  usuario_id uuid default auth.uid() references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists movimientos_caja_fecha_idx on public.movimientos_caja(fecha_movimiento desc);
create index if not exists movimientos_caja_ref_idx on public.movimientos_caja(referencia_tipo,referencia_id);

create table if not exists public.presupuestos (
  id bigint generated by default as identity primary key,
  folio text not null unique,
  cliente text not null,
  telefono text default '',
  equipo text not null,
  conceptos jsonb not null default '[]'::jsonb,
  total numeric(12,2) not null default 0 check (total >= 0),
  estado text not null default 'Borrador',
  notas text default '',
  orden_id bigint references public.ordenes(id) on delete set null,
  venta_id bigint references public.ventas(id) on delete set null,
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now(),
  creado_por uuid default auth.uid() references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists presupuestos_estado_idx on public.presupuestos(estado);
create index if not exists presupuestos_fecha_idx on public.presupuestos(creado_en desc);

