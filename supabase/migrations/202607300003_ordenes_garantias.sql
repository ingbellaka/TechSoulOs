-- RLS homogéneo para las tablas del sprint.
do $$
declare t text;
begin
  foreach t in array array['ordenes','checklist_orden','evidencias','orden_historial','firmas_orden','configuracion_garantias','garantias','reclamaciones_garantia'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists %I on public.%I', t || '_leer', t);
    execute format('create policy %I on public.%I for select to authenticated using (public.mi_rol() is not null)', t || '_leer', t);
    execute format('drop policy if exists %I on public.%I', t || '_insertar', t);
    execute format('create policy %I on public.%I for insert to authenticated with check (public.mi_rol() in (''admin'',''recepcion'',''tecnico''))', t || '_insertar', t);
    execute format('drop policy if exists %I on public.%I', t || '_actualizar', t);
    execute format('create policy %I on public.%I for update to authenticated using (public.mi_rol() in (''admin'',''recepcion'',''tecnico'')) with check (public.mi_rol() in (''admin'',''recepcion'',''tecnico''))', t || '_actualizar', t);
    execute format('drop policy if exists %I on public.%I', t || '_eliminar', t);
    execute format('create policy %I on public.%I for delete to authenticated using (public.es_admin())', t || '_eliminar', t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
  end loop;
end $$;
grant usage, select on all sequences in schema public to authenticated;

