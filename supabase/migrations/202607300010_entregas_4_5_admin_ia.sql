create table if not exists public.roles_sistema (
  clave text primary key,
  nombre text not null,
  descripcion text not null default '',
  activo boolean not null default true,
  creado_en timestamptz not null default now()
);

create table if not exists public.permisos_sistema (
  id bigint generated by default as identity primary key,
  rol_clave text not null references public.roles_sistema(clave) on update cascade on delete cascade,
  modulo text not null,
  puede_ver boolean not null default false,
  puede_crear boolean not null default false,
  puede_editar boolean not null default false,
  puede_eliminar boolean not null default false,
  puede_cobrar boolean not null default false,
  actualizado_en timestamptz not null default now(),
  unique (rol_clave, modulo)
);

create table if not exists public.metodos_pago_config (
  id bigint generated by default as identity primary key,
  nombre text not null unique,
  activo boolean not null default true,
  requiere_referencia boolean not null default false,
  orden integer not null default 0,
  creado_en timestamptz not null default now()
);

