select r.clave, m.modulo,
  true,
  case when r.clave='admin' then true when r.clave='recepcion' then m.modulo not in ('usuarios','configuracion','auditoria') else m.modulo in ('ordenes','equipos','garantias') end,
  case when r.clave='admin' then true when r.clave='recepcion' then m.modulo not in ('usuarios','configuracion','auditoria') else m.modulo in ('ordenes','equipos','garantias') end,
  r.clave='admin',
  r.clave in ('admin','recepcion') and m.modulo in ('ordenes','caja','ventas')
from public.roles_sistema r
cross join (values ('dashboard'),('clientes'),('equipos'),('ordenes'),('inventario'),('compras'),('ventas'),('caja'),('reportes'),('garantias'),('catalogo'),('conocimiento'),('usuarios'),('configuracion'),('auditoria')) m(modulo)
on conflict (rol_clave,modulo) do nothing;

