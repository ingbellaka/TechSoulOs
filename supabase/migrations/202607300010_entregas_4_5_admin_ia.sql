create or replace view public.v_base_conocimiento_ia as
select 'faq'::text as tipo, id::text as referencia_id, pregunta as titulo, respuesta as contenido,
       categoria, palabras_clave, prioridad, activo, actualizado_en
from public.faq
union all
select 'plantilla', id::text, nombre, contenido, categoria, palabras_clave, 0, activo, actualizado_en
from public.plantillas_respuesta
union all
select 'promocion', id::text, nombre, concat_ws(E'\n',descripcion,condiciones), 'Promociones',
       array['promoción','oferta']::text[], 20, activo, actualizado_en
from public.promociones
where (fecha_inicio is null or fecha_inicio <= current_date) and (fecha_fin is null or fecha_fin >= current_date)
union all
select 'servicio', id::text, nombre,
       concat_ws(E'\n',descripcion, respuesta_cotizacion, recomendaciones, preguntas_frecuentes, instrucciones_agente),
       coalesce(categoria,'Servicios'), coalesce(palabras_clave,'{}'::text[]), 50, activo, coalesce(actualizado_en,now())
from public.catalogo_servicios;

create or replace function public.buscar_conocimiento_ia(termino text, limite integer default 12)
returns table(tipo text, referencia_id text, titulo text, contenido text, categoria text, palabras_clave text[], prioridad integer)
language sql stable security invoker as $$
  select b.tipo,b.referencia_id,b.titulo,b.contenido,b.categoria,b.palabras_clave,b.prioridad
  from public.v_base_conocimiento_ia b
  where b.activo = true and (
    b.titulo ilike '%'||coalesce(termino,'')||'%' or
    b.contenido ilike '%'||coalesce(termino,'')||'%' or
    b.categoria ilike '%'||coalesce(termino,'')||'%' or
    exists(select 1 from unnest(coalesce(b.palabras_clave,'{}'::text[])) p where p ilike '%'||coalesce(termino,'')||'%')
  )
  order by b.prioridad desc, b.titulo
  limit greatest(1,least(coalesce(limite,12),50));
$$;

